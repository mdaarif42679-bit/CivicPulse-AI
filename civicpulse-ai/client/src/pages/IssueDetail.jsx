import { useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { ArrowLeft, CheckCircle2, Clock, Info, MapPin, RotateCcw, ShieldCheck } from 'lucide-react';
import { api } from '../services/api.js';
import { useFetch } from '../hooks/useFetch.js';
import { useApp } from '../context.jsx';
import { ErrorBox, Loading } from '../components/States.jsx';
import { AiTag, SeverityBadge, StatusBadge, UserTag } from '../components/Badges.jsx';
import { fmtDateTime, pct, pluralize } from '../utils/format.js';

export default function IssueDetail() {
  const { id } = useParams();
  const { refresh, toast } = useApp();
  const { data, error, loading, reload } = useFetch(() => api.issue(id), [id]);
  const [busy, setBusy] = useState(false);
  if (error) return <ErrorBox error={error} retry={reload} />;
  if (loading || !data) return <Loading rows={5} />;
  const { issue, reports, evidence } = data;
  const b = issue.summary;
  const act = async (fn, msg) => { setBusy(true); try { await fn(); toast(msg); refresh(); } catch (e) { toast(e.message, 'err'); } finally { setBusy(false); } };

  const timeline = [
    ...reports.map((r) => ({ ts: r.timestamp, kind: 'user', text: `Report submitted: "${(r.description || 'voice report').slice(0, 90)}"`, link: `/reports/${r.id}` })),
    ...issue.events.map((e) => ({ ts: e.ts, kind: e.type === 'status' ? 'human' : 'ai', text: e.text })),
  ].sort((a, b2) => a.ts.localeCompare(b2.ts));
  const imgs = evidence.filter((e) => e.type === 'image'), auds = evidence.filter((e) => e.type === 'audio');

  return (
    <>
      <Link to="/issues" className="muted row" style={{ marginBottom: 12 }}><ArrowLeft size={15} /> All issues</Link>
      <div className="page-head">
        <div>
          <h1>{issue.title}</h1>
          <div className="row" style={{ marginTop: 8 }}>
            <SeverityBadge level={issue.severity} /><StatusBadge status={issue.status} /><span className="chip">{issue.category}</span>
            <span className="muted row" style={{ gap: 4 }}><MapPin size={14} /> {issue.location}</span>
          </div>
        </div>
        <div className="row">
          {issue.status !== 'Verified' && issue.status !== 'Resolved' && <button className="btn primary" disabled={busy} onClick={() => act(() => api.verify(issue.id), 'Marked as verified')}><ShieldCheck size={16} /> Mark as verified</button>}
          {issue.status !== 'Resolved' ? <button className="btn" disabled={busy} onClick={() => act(() => api.setStatus(issue.id, 'Resolved'), 'Marked as resolved')}><CheckCircle2 size={16} /> Mark resolved</button>
            : <button className="btn" disabled={busy} onClick={() => act(() => api.setStatus(issue.id, 'Needs Verification'), 'Issue reopened')}><RotateCcw size={16} /> Reopen</button>}
        </div>
      </div>

      <div className="grid g5" style={{ gridTemplateColumns: 'repeat(4,1fr)', marginBottom: 16 }}>
        <div className="card stat"><div className="l">Related reports</div><div className="n">{issue.reportCount}</div></div>
        <div className="card stat"><div className="l">Evidence files</div><div className="n">{issue.evidenceCount}</div></div>
        <div className="card stat"><div className="l">Grouping confidence</div><div className="n">{pct(issue.confidence)}</div><div className="muted" style={{ fontSize: 12 }}>AI-estimated</div></div>
        <div className="card stat"><div className="l">Verification</div><div className="n" style={{ fontSize: 20, marginTop: 10 }}>{issue.status === 'Needs Verification' ? 'Not verified' : issue.status}</div></div>
      </div>

      <div className="split">
        <div className="grid">
          <section className="ai-panel" aria-label="AI-generated brief">
            <div className="card-head"><h2>Issue brief</h2><AiTag>AI-generated insight</AiTag></div>
            {b ? <dl className="kv" style={{ margin: 0 }}>
              <dt>What happened</dt><dd>{b.whatHappened}</dd>
              <dt>Where</dt><dd>{b.where}</dd>
              <dt>Evidence</dt><dd>{b.evidence}</dd>
              <dt>Possible impact</dt><dd>{b.impact}</dd>
              <dt>Needs verification</dt><dd><ul style={{ margin: 0, paddingLeft: 18 }}>{b.needsVerification.map((n) => <li key={n}>{n}</li>)}</ul></dd>
              <dt>Status</dt><dd>{issue.status}</dd>
            </dl> : <p className="muted">No brief yet.</p>}
            <div className="notice" style={{ marginTop: 14 }}><Info size={16} style={{ flex: 'none', marginTop: 2 }} />
              <span className="muted">Generated by {b?.source === 'gemini' ? 'Gemini' : 'template-based fallback logic (Demo Mode)'}. It summarizes user reports and has not been verified. Confirm on site before acting.</span></div>
          </section>

          <section className="user-panel" aria-label="Supporting reports">
            <div className="card-head"><h2>Supporting reports</h2><UserTag /></div>
            <div className="list">
              {reports.map((r) => (
                <Link className="item" style={{ gridTemplateColumns: '1fr auto' }} key={r.id} to={`/reports/${r.id}`}>
                  <div><div className="t wrap">{r.description || '(voice report)'}</div>
                    <div className="s">{fmtDateTime(r.timestamp)} · {r.location || r.aiAnalysis?.location || 'No location'}{r.imageUrl ? ' · photo' : ''}</div></div>
                  {typeof r.clusterScore === 'number' ? <span className="chip" title="Similarity when grouped">sim {r.clusterScore.toFixed(2)}</span> : <span className="chip">first report</span>}
                </Link>))}
            </div>
          </section>
        </div>

        <div className="grid">
          <section className="user-panel" aria-label="Evidence">
            <div className="card-head"><h2>Evidence</h2><UserTag /></div>
            {evidence.length === 0 ? <p className="muted">No photos or audio attached to these reports.</p> : <>
              {imgs.length > 0 && <div className="gallery">{imgs.map((e) => <a key={e.id} href={e.url} target="_blank" rel="noreferrer"><img src={e.url} alt="Evidence uploaded by a reporter" loading="lazy" /></a>)}</div>}
              {auds.map((e) => <audio key={e.id} controls src={e.url} style={{ width: '100%', marginTop: 10 }} />)}
            </>}
            {imgs.some((e) => e.url.includes('demo-gate')) && <p className="muted" style={{ fontSize: 12, marginTop: 10 }}>Demo images are illustrations, not real photos.</p>}
          </section>
          <section className="card" aria-label="Timeline">
            <div className="card-head"><h2>Timeline</h2><Clock size={16} color="var(--muted)" /></div>
            <ul className="timeline">
              {timeline.map((t, i) => (
                <li key={i} className={t.kind}>
                  <time>{fmtDateTime(t.ts)} · {t.kind === 'user' ? 'Reporter' : t.kind === 'ai' ? 'AI grouping' : 'Human review'}</time>
                  {t.link ? <Link to={t.link} className="wrap">{t.text}</Link> : <span>{t.text}</span>}
                </li>))}
            </ul>
            <p className="muted" style={{ fontSize: 12 }}>{pluralize(reports.length, 'report')} grouped into this issue.</p>
          </section>
        </div>
      </div>
    </>
  );
}
